#!/usr/bin/env python3
"""
make_room_themes.py - builds ha/themes/neon_room.yaml from ha/themes/neon_club.yaml: the same Neon Club look in
13 room colors (12 hues + warm white). The automation "Dashboard follows the room lights" switches between them
(sensor.room_light_theme picks the one matching the brightest bedroom light; Neon Club when the lights are off).

  py tools/ha_setup/make_room_themes.py
"""
import colorsys
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "home_assistant", "themes", "neon_club.yaml")
OUT = os.path.join(ROOT, "home_assistant", "themes", "neon_room.yaml")

HUES = ["Red", "Orange", "Yellow", "Lime", "Green", "Teal", "Cyan", "Azure", "Blue", "Violet", "Magenta", "Pink"]
# Neon Club's colors and what each becomes in a room theme
PINK, PINK_RGB = "#ff2bd6", "255, 43, 214"      # accent
CYAN, CYAN_RGB = "#22e4ff", "34, 228, 255"      # second glow
VIOLET, VIOLET_RGB = "#8b5cff", "139, 92, 255"  # card edges


def color(h, s=0.84, v=1.0):
    r, g, b = (round(c * 255) for c in colorsys.hsv_to_rgb((h % 360) / 360, s, v))
    return f"#{r:02x}{g:02x}{b:02x}", f"{r}, {g}, {b}"


def variant(base, name, accent, second, edge):
    t = base.replace("Neon Club:", f"{name}:", 1)
    for old, new in ((PINK, accent[0]), (PINK_RGB, accent[1]), (CYAN, second[0]), (CYAN_RGB, second[1]),
                     (VIOLET, edge[0]), (VIOLET_RGB, edge[1])):
        t = t.replace(old, new)
    return t


def main():
    with open(SRC, encoding="utf-8") as f:
        lines = f.read().splitlines()
    body = "\n".join(l for l in lines if not l.startswith("#")).strip() + "\n"   # the theme without the file comments
    out = ["# GENERATED by tools/ha_setup/make_room_themes.py from neon_club.yaml - edit that file, then run the script.",
           "# Neon Club in the color of the room lights; picked by sensor.room_light_theme, applied by the automation",
           "# 'Smart home · Dashboard follows the room lights'.", ""]
    for i, name in enumerate(HUES):
        h = i * 30
        out.append(variant(body, f"Neon Room {name}", color(h), color(h + 45, 0.8), color(h - 25, 0.7)))
    out.append(variant(body, "Neon Room Warm", ("#ffb02e", "255, 176, 46"), ("#ff6a3d", "255, 106, 61"), ("#ff8a2b", "255, 138, 43")))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(HUES) + 1} themes")


if __name__ == "__main__":
    main()
